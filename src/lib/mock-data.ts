import type { MarketBrief, SectorFlow, TideStatus } from "./types";

function statusOf(d5: number, accel: number): TideStatus {
  if (d5 >= 0 && accel >= 0) return "surge";
  if (d5 >= 0 && accel < 0) return "rotate";
  if (d5 < 0 && accel >= 0) return "watch";
  return "ebb";
}

type Seed = Omit<SectorFlow, "status" | "id"> & { id?: string };

function sector(seed: Seed): SectorFlow {
  const id =
    seed.id ??
    seed.name
      .toLowerCase()
      .replace(/\s+/g, "-")
      .replace(/[^\w\u4e00-\u9fff-]/g, "");
  return {
    ...seed,
    id,
    status: statusOf(seed.d5, seed.accel),
  };
}

